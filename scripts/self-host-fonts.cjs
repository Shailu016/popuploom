/* Self-host the site's web fonts.

   Downloads the latin subset of each family from the Google Fonts CSS API (the
   files are the official releases, all under the SIL Open Font Licence 1.1),
   saves them as content-hashed .woff2 files in assets/fonts/, and writes:
     assets/fonts/manifest.json   file names used by scripts/enhance-content-pages.cjs
     the @font-face block in ui.css between the FONTS markers

   Pages then load fonts from this origin: no third-party request, one cache
   rule (immutable, the file names carry a hash). Re-run only to change which
   families or weights ship:
     node scripts/self-host-fonts.cjs

   Licences: assets/fonts/LICENSES.txt is maintained by hand (copied from each
   family's repository). This script refuses to finish if a family it downloads
   has no entry there. */
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const root = path.resolve(__dirname, "..");
const dir = path.join(root, "assets", "fonts");
fs.mkdirSync(dir, { recursive: true });

const CSS_URL = "https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,600;12..96,700;12..96,800&family=Geist:wght@400;500;600;700&family=Geist+Mono:wght@400;500&family=Instrument+Serif:ital@0;1&display=swap";
// A current Chrome user agent makes the API answer with woff2 files.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";
const KEEP = new Set(["latin"]);

async function get(url, binary) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(url + " -> " + res.status);
  return binary ? Buffer.from(await res.arrayBuffer()) : await res.text();
}

(async () => {
  const css = await get(CSS_URL, false);
  const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
  if (!blocks.length) throw new Error("No @font-face blocks in the CSS response");
  // Parse everything first, so licences are checked before anything is downloaded or written.
  const parsed = [];
  for (const [, subset, body] of blocks) {
    if (!KEEP.has(subset)) continue;
    const family = (body.match(/font-family:\s*'([^']+)'/) || [])[1];
    const style = (body.match(/font-style:\s*(\w+)/) || [])[1] || "normal";
    const weight = (body.match(/font-weight:\s*([\d ]+)/) || [])[1].trim();
    const url = (body.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
    const range = (body.match(/unicode-range:\s*([^;]+)/) || [])[1];
    if (!family || !url) throw new Error("Could not parse a font-face block for " + subset);
    parsed.push({ subset, family, style, weight, url, range });
  }
  // Never ship a family without its licence text: LICENSES.txt must name every family.
  const squash = (x) => String(x).toLowerCase().replace(/[^a-z]/g, "");
  const licencePath = path.join(dir, "LICENSES.txt");
  const licences = fs.existsSync(licencePath) ? squash(fs.readFileSync(licencePath, "utf8")) : "";
  const unlicensed = [...new Set(parsed.map((p) => p.family))].filter((fam) => !licences.includes(squash(fam)));
  if (unlicensed.length) throw new Error("No licence text in assets/fonts/LICENSES.txt for: " + unlicensed.join(", ") + ". Add its OFL text first. Nothing was downloaded or changed.");

  const faces = [];
  for (const { subset, family, style, weight, url, range } of parsed) {
    const buf = await get(url, true);
    if (buf.slice(0, 4).toString("latin1") !== "wOF2") throw new Error(family + ": downloaded file is not woff2");
    const hash = crypto.createHash("sha256").update(buf).digest("hex").slice(0, 10);
    const file = `${family.toLowerCase().replace(/\s+/g, "-")}-${style}-${subset}.${hash}.woff2`;
    fs.writeFileSync(path.join(dir, file), buf);
    // Variable fonts come back as one identical file per requested weight: keep one, widen the weight range.
    const prior = faces.find((x) => x.file === file);
    if (prior) { prior.weights.push(+weight); continue; }
    faces.push({ family, style, weights: [+weight], file, range, bytes: buf.length });
  }
  // remove files from an older run
  const keep = new Set(faces.map((f) => f.file).concat(["manifest.json", "LICENSES.txt"]));
  for (const f of fs.readdirSync(dir)) if (/\.woff2$/.test(f) && !keep.has(f)) fs.unlinkSync(path.join(dir, f));
  fs.writeFileSync(path.join(dir, "manifest.json"), JSON.stringify(faces, null, 2) + "\n");

  const rules = faces.map((f) => `@font-face { font-family: "${f.family}"; font-style: ${f.style}; font-weight: ${f.weights.length > 1 ? Math.min(...f.weights) + " " + Math.max(...f.weights) : f.weights[0]}; font-display: swap; src: url("/assets/fonts/${f.file}") format("woff2"); unicode-range: ${f.range}; }`).join("\n");
  const block = `/* FONTS:begin (generated by scripts/self-host-fonts.cjs) */\n${rules}\n/* FONTS:end */`;
  const cssPath = path.join(root, "ui.css");
  const raw = fs.readFileSync(cssPath, "utf8");
  const crlf = raw.includes("\r\n");
  let s = raw.replace(/\r\n/g, "\n");
  if (/\/\* FONTS:begin[\s\S]*?\/\* FONTS:end \*\//.test(s)) s = s.replace(/\/\* FONTS:begin[\s\S]*?\/\* FONTS:end \*\//, () => block);
  else s = s.replace(/(\*\/\n)(\n?:root \{)/, (m, a, b) => a + "\n" + block + "\n" + b);
  fs.writeFileSync(cssPath, crlf ? s.replace(/\n/g, "\r\n") : s);
  const total = faces.reduce((n, f) => n + f.bytes, 0);
  console.log(`self-hosted ${faces.length} font files, ${(total / 1024).toFixed(0)} KB`);
  faces.forEach((f) => console.log(" ", f.family, f.style, f.weights.join("/"), (f.bytes / 1024).toFixed(1) + " KB"));
})().catch((e) => { console.error(e.message); process.exit(1); });
