// scripts/export-db.js — dump popforge.db to worker/migrations/0002_data.sql for D1.
// Preserve password hashes; Workers upgrades legacy hashes after successful login.
const fs = require("fs");
const path = require("path");
const { DatabaseSync } = require("node:sqlite");

const DB_PATH = process.env.DB_PATH || path.join(__dirname, "..", "popforge.db");
const OUT_PATH = path.resolve(process.env.EXPORT_PATH || path.join(__dirname, "..", "private-data", "snapshot.sql"));

const db = new DatabaseSync(DB_PATH, { readOnly: true });

function esc(value) {
  if (value === null || value === undefined) return "NULL";
  return "'" + String(value).replace(/'/g, "''") + "'";
}

async function main() {
  // Read columns dynamically: live databases may predate later migrations.
  const userCols = db.prepare("PRAGMA table_info(users)").all().map(c => c.name);
  const hasTokenVersion = userCols.includes("token_version");
  const users = db.prepare("SELECT * FROM users ORDER BY id").all();

  const widgetCols = db.prepare("PRAGMA table_info(widgets)").all().map(c => c.name);
  const widgets = db.prepare("SELECT * FROM widgets ORDER BY id").all();

  const subCols = db.prepare("PRAGMA table_info(submissions)").all().map(c => c.name);
  const hasRequestId = subCols.includes("request_id");
  const submissions = db.prepare("SELECT * FROM submissions ORDER BY id").all();

  const tables = db.prepare("SELECT name FROM sqlite_master WHERE type = 'table'").all().map(t => t.name);
  const revoked = tables.includes("revoked_tokens") ? db.prepare("SELECT token_hash, expires_at FROM revoked_tokens").all() : [];

  const lines = [
    "-- Auto-generated by scripts/export-db.js: PopForge data snapshot for D1.",
    "-- Regenerate with `npm run db:export` before a fresh deploy."
  ];

  for (const u of users) {
    let hash = u.password_hash, tokenVersion = hasTokenVersion ? u.token_version : 0;
    lines.push(`INSERT INTO users (id, email, password_hash, created_at, token_version, google_id, name, avatar_url) VALUES (${u.id}, ${esc(u.email)}, ${esc(hash)}, ${esc(u.created_at)}, ${tokenVersion}, ${esc(u.google_id)}, ${esc(u.name)}, ${esc(u.avatar_url)});`);
  }
  for (const w of widgets) lines.push(`INSERT INTO widgets (id, user_id, name, template, config, view_count, created_at, updated_at) VALUES (${esc(w.id)}, ${w.user_id}, ${esc(w.name)}, ${esc(w.template)}, ${esc(w.config)}, ${w.view_count}, ${esc(w.created_at)}, ${esc(w.updated_at)});`);
  for (const s of submissions) lines.push(`INSERT INTO submissions (id, widget_id, data, created_at, request_id) VALUES (${s.id}, ${esc(s.widget_id)}, ${esc(s.data)}, ${esc(s.created_at)}, ${esc(hasRequestId ? s.request_id : null)});`);
  for (const r of revoked) lines.push(`INSERT INTO revoked_tokens (token_hash, expires_at) VALUES (${esc(r.token_hash)}, ${r.expires_at});`);

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  if (fs.existsSync(OUT_PATH)) throw new Error("Export already exists; choose a new EXPORT_PATH");
  fs.writeFileSync(OUT_PATH, lines.join("\n") + "\n");
  console.log(`Wrote ${OUT_PATH}: ${users.length} users, ${widgets.length} widgets, ${submissions.length} submissions, ${revoked.length} revoked tokens`);
  db.close();
}

main().catch(e => { console.error(e); process.exit(1); });
