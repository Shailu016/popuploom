define( 'POPUPLOOM_OPTION', 'popuploom_widget_id' );
define( 'POPUPLOOM_SCRIPT', 'https://popuploom.com/embed/1.1.0/popuploom.js' );
define( 'POPUPLOOM_RUNTIME_VERSION', '1.1.0' );

/**
 * Widget IDs are generated by PopupLoom as wan_ followed by hex characters.
 * Reject anything else so a saved value can never inject markup or a remote URL.
 */
function popuploom_is_valid_widget_id( $value ) {
	return is_string( $value ) && 1 === preg_match( '/^wan_[A-Za-z0-9]{6,64}$/', $value );
}

function popuploom_sanitize_widget_id( $value ) {
	$value = is_string( $value ) ? trim( $value ) : '';
	return popuploom_is_valid_widget_id( $value ) ? $value : '';
}

function popuploom_register_settings() {
	register_setting(
		'popuploom',
		POPUPLOOM_OPTION,
		array(
			'type'              => 'string',
			'sanitize_callback' => 'popuploom_sanitize_widget_id',
			'default'           => '',
			'show_in_rest'      => false,
		)
	);
}
add_action( 'admin_init', 'popuploom_register_settings' );

function popuploom_settings_menu() {
	add_options_page(
		__( 'PopupLoom', 'popuploom' ),
		__( 'PopupLoom', 'popuploom' ),
		'manage_options',
		'popuploom',
		'popuploom_settings_page'
	);
}
add_action( 'admin_menu', 'popuploom_settings_menu' );

function popuploom_settings_link( $links ) {
	$url = admin_url( 'options-general.php?page=popuploom' );
	array_unshift( $links, '<a href="' . esc_url( $url ) . '">' . esc_html__( 'Settings', 'popuploom' ) . '</a>' );
	return $links;
}
add_filter( 'plugin_action_links_' . plugin_basename( __FILE__ ), 'popuploom_settings_link' );

