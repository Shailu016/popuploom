/**
 * Register the hosted runtime through the WordPress script API so caching and
 * optimization plugins can see it. Footer loading keeps it out of the critical
 * path; a null version keeps the immutable URL free of a query string.
 */
function popuploom_enqueue_runtime() {
	if ( is_admin() || is_feed() || is_robots() ) {
		return;
	}
	$widget_id = popuploom_sanitize_widget_id( get_option( POPUPLOOM_OPTION, '' ) );
	if ( '' === $widget_id ) {
		return;
	}
	wp_enqueue_script( 'popuploom-embed', POPUPLOOM_SCRIPT, array(), POPUPLOOM_RUNTIME_VERSION, true );
}
add_action( 'wp_enqueue_scripts', 'popuploom_enqueue_runtime' );

/**
 * Print the widget mount point in the footer. The runtime itself is enqueued
 * above; this only outputs the element the runtime looks for.
 */
function popuploom_render_footer() {
	if ( is_admin() || is_feed() || is_robots() ) {
		return;
	}
	$widget_id = popuploom_sanitize_widget_id( get_option( POPUPLOOM_OPTION, '' ) );
	if ( '' === $widget_id ) {
		return;
	}
	printf( '<div data-popuploom="%s"></div>' . "\n", esc_attr( $widget_id ) );
}
add_action( 'wp_footer', 'popuploom_render_footer', 99 );
